import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { mkTmp } from "./helpers/tmp";
import { ROOT, CLI } from "./helpers/run-cli";

// Runs the action's shell steps (scripts/action/*.sh) the way action.yml does, with a fake `gh` on PATH.
const hasTools = process.platform !== "win32" && spawnSync("git", ["--version"]).status === 0 && spawnSync("bash", ["--version"]).status === 0;
const d = hasTools ? describe : describe.skip;

const sh = (cmd: string[], cwd: string, env: Record<string, string> = {}) => spawnSync(cmd[0], cmd.slice(1), { cwd, encoding: "utf8", env: { ...process.env, ...env } });

function repo() {
  const dir = mkTmp("prehello-action-repo-");
  const git = (...a: string[]) => {
    const r = sh(["git", "-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false", ...a], dir);
    if (r.status !== 0) throw new Error(r.stderr);
    return r.stdout.trim();
  };
  git("init", "-q", "-b", "main");
  fs.writeFileSync(path.join(dir, "CLAUDE.md"), "Use pnpm.\n");
  git("add", "-A");
  git("commit", "-q", "-m", "base");
  const base = git("rev-parse", "HEAD");
  fs.writeFileSync(path.join(dir, "CLAUDE.md"), "Use pnpm.\n" + "Keep functions small and test everything you change.\n".repeat(80));
  fs.mkdirSync(path.join(dir, ".cursor", "rules"), { recursive: true });
  fs.writeFileSync(path.join(dir, ".cursor", "rules", "x.mdc"), "---\nalwaysApply: true\n---\nBe brief.\n");
  git("add", "-A");
  git("commit", "-q", "-m", "head");
  return { dir, base };
}

function fakeGh(bin: string) {
  fs.mkdirSync(bin, { recursive: true });
  fs.writeFileSync(
    path.join(bin, "gh"),
    `#!/usr/bin/env bash
echo "$*" >> "$GH_LOG"
if [[ "$*" == *"-X "* ]]; then
  [ "\${GH_FAIL:-0}" = 1 ] && exit 1
  while [ $# -gt 0 ]; do [ "$1" = "--input" ] && cp "$2" "$GH_BODY"; shift; done
  exit 0
fi
[ -n "\${GH_EXISTING:-}" ] && echo "$GH_EXISTING"
exit 0
`,
    { mode: 0o755 },
  );
  // an agent installed on the runner (a `cursor` binary on PATH) must not change the result: only repository files count
  fs.writeFileSync(path.join(bin, "cursor"), "#!/bin/sh\nexit 0\n", { mode: 0o755 });
}

function run(env: Record<string, string>) {
  const { dir, base } = repo();
  const tmp = mkTmp("prehello-action-runner-");
  const bin = path.join(tmp, "bin");
  fakeGh(bin);
  const e = {
    RUNNER_TEMP: tmp,
    GITHUB_WORKSPACE: dir,
    GITHUB_OUTPUT: path.join(tmp, "out"),
    GITHUB_STEP_SUMMARY: path.join(tmp, "summary"),
    PREHELLO_BIN: CLI,
    BASE_SHA: base,
    SCAN_PATH: ".",
    GH_LOG: path.join(tmp, "gh.log"),
    GH_BODY: path.join(tmp, "body.json"),
    GH_TOKEN: "x",
    REPO: "o/r",
    PR_NUMBER: "7",
    PATH: `${bin}:${process.env.PATH}`,
    ...env,
  };
  const step = (s: string) => sh(["bash", path.join(ROOT, "scripts", "action", s)], dir, e);
  return { dir, tmp, e, scan: step("scan.sh"), diff: () => step("diff.sh"), comment: () => step("comment.sh") };
}
const read = (f: string) => (fs.existsSync(f) ? fs.readFileSync(f, "utf8") : "");

d("GitHub Action scripts (simulated runner)", () => {
  it("scans base and head, writes the summary and outputs, posts one comment", () => {
    const r = run({});
    expect(r.scan.stderr).toBe("");
    expect(r.scan.status).toBe(0);
    const df = r.diff();
    expect(df.status).toBe(0);
    const summary = read(r.e.GITHUB_STEP_SUMMARY);
    expect(summary.startsWith("<!-- generated by prehello diff -->")).toBe(true);
    expect(summary).toMatch(/`Claude Code` \| \d+ \| [\d.k]+ \| \*\*\+/);
    expect(summary).toMatch(/`Cursor` \| - \|/);
    expect(read(r.e.GITHUB_OUTPUT)).toMatch(/^delta=\d+\nover=false\n$/);
    const c = r.comment();
    expect(c.status).toBe(0);
    expect(read(r.e.GH_LOG)).toMatch(/-X POST repos\/o\/r\/issues\/7\/comments/);
    expect(JSON.parse(read(r.e.GH_BODY)).body).toBe(summary);
    // the base worktree is cleaned up
    expect(sh(["git", "worktree", "list"], r.dir).stdout.trim().split("\n").length).toBe(1);
  });
  it("updates the existing sticky comment instead of adding another", () => {
    const r = run({ GH_EXISTING: "4242" });
    r.diff();
    expect(r.comment().status).toBe(0);
    const log = read(r.e.GH_LOG);
    expect(log).toMatch(/-X PATCH repos\/o\/r\/issues\/comments\/4242/);
    expect(log).not.toMatch(/-X POST/);
  });
  it("fail-above: reports over=true (the action then fails after commenting)", () => {
    const r = run({ FAIL_ABOVE: "100" });
    expect(r.diff().status).toBe(0);
    expect(read(r.e.GITHUB_OUTPUT)).toMatch(/over=true/);
    expect(read(r.e.GITHUB_STEP_SUMMARY)).toMatch(/Over the limit/);
  });
  it("fork PR (read-only token): the comment step warns and succeeds", () => {
    const r = run({ GH_FAIL: "1" });
    r.diff();
    const c = r.comment();
    expect(c.status).toBe(0);
    expect(c.stdout).toMatch(/::warning::.*fork/);
  });
  it("rejects a path that leaves the repository", () => {
    const r = run({ SCAN_PATH: "../etc" });
    expect(r.scan.status).toBe(1);
    expect(r.scan.stdout).toMatch(/::error::path/);
  });
  it("no base sha (push event): compares head with itself", () => {
    const r = run({ BASE_SHA: "" });
    expect(r.scan.status).toBe(0);
    r.diff();
    expect(read(r.e.GITHUB_STEP_SUMMARY)).toMatch(/No change in always-on context/);
  });
});
