/**
 * `prehello diff base.json head.json`: compare two saved reports (from `prehello --save` / `--json=`). Offline, no git:
 * the GitHub Action (action.yml) produces the two snapshots. Item names come from the scanned repository, so every one
 * goes through mdCode / sanitize before it is printed.
 */
import { fmtTok, sanitize } from "./util/fmt";
import { mdCode } from "./render/markdown";
import { REPO_URL } from "./render/card";

/** Starts with MD_MARKER_PREFIX (so --markdown=<file> can overwrite its own output) and is the sticky-comment marker the Action looks for. */
export const DIFF_MARKER = "<!-- generated by prehello diff -->";

interface SnapTokens { est: number; low: number; high: number }
interface SnapItem { id?: string; kind: string; loadMode: string; label?: string; path?: string; tokens: SnapTokens | null }
interface SnapAgent { id: string; name: string; detected?: boolean; presentInRepoOnly?: boolean; totals: Record<string, SnapTokens & { unmeasuredItems?: number }>; alwaysIsLowerBound?: boolean; profile?: { id?: string }; items?: SnapItem[] }
export interface Snapshot { schemaVersion: number | string; tool: { name: string; version: string }; scan?: { tokenizer?: { method?: string }; window?: number }; agents: SnapAgent[] }

export class DiffInputError extends Error {}

export function parseSnapshot(text: string, what: string): Snapshot {
  let j: unknown;
  try {
    j = JSON.parse(text.replace(/^\uFEFF/, ""));
  } catch {
    throw new DiffInputError(`${what} is not JSON; create it with: prehello --save ${what}`);
  }
  const s = j as Snapshot;
  if (!s || typeof s !== "object" || s.tool?.name !== "prehello" || !Array.isArray(s.agents) || s.schemaVersion === undefined) {
    throw new DiffInputError(`${what} is not a prehello report; create it with: prehello --save ${what}`);
  }
  return s;
}

export interface ItemChange { key: string; label: string; kind: string; base: number | null; head: number | null; delta: number }
export interface AgentDiff {
  id: string;
  name: string;
  base: number | null;
  head: number | null;
  delta: number;
  deltaPct: number | null;
  deferredDelta: number;
  lowerBound: boolean;
  changes: ItemChange[];
  moreChanges: number;
}
export interface DiffResult { base: Snapshot; head: Snapshot; agents: AgentDiff[]; notes: string[] }

const MAX_ITEMS = 10;
const itemKey = (i: SnapItem) => `${i.kind}|${i.loadMode}|${i.path ?? i.label ?? i.id ?? ""}`;
/** Counted when installed or when the repository has files for it (a CI runner has no agent installed). */
const active = (a: SnapAgent | undefined) => !!a && (!!a.detected || (a.items?.length ?? 0) > 0);

export function diffSnapshots(base: Snapshot, head: Snapshot): DiffResult {
  const notes: string[] = [];
  if (String(base.schemaVersion) !== String(head.schemaVersion)) notes.push(`report schema differs (base ${base.schemaVersion}, head ${head.schemaVersion}); numbers may not be comparable`);
  if (base.scan?.tokenizer?.method !== head.scan?.tokenizer?.method) notes.push("base and head were counted with different tokenizers");
  if (base.tool.version !== head.tool.version) notes.push(`made by different prehello versions (base ${sanitize(base.tool.version, 20)}, head ${sanitize(head.tool.version, 20)}); part of the change may be the estimator`);
  const ids = [...new Set([...base.agents, ...head.agents].map((a) => a.id))];
  const agents: AgentDiff[] = [];
  for (const id of ids) {
    const b = base.agents.find((a) => a.id === id);
    const h = head.agents.find((a) => a.id === id);
    if (!active(b) && !active(h)) continue;
    const bt = active(b) ? b!.totals.always.est : null;
    const ht = active(h) ? h!.totals.always.est : null;
    const delta = (ht ?? 0) - (bt ?? 0);
    const deferredDelta = (active(h) ? h!.totals.deferred?.est ?? 0 : 0) - (active(b) ? b!.totals.deferred?.est ?? 0 : 0);
    if (b?.profile?.id && h?.profile?.id && b.profile.id !== h.profile.id) notes.push(`${sanitize(h.name, 40)}: estimate profile changed (${sanitize(b.profile.id, 30)} -> ${sanitize(h.profile.id, 30)})`);
    const bi = new Map((active(b) ? b!.items ?? [] : []).filter((i) => i.loadMode === "always").map((i) => [itemKey(i), i]));
    const hi = new Map((active(h) ? h!.items ?? [] : []).filter((i) => i.loadMode === "always").map((i) => [itemKey(i), i]));
    const changes: ItemChange[] = [];
    for (const k of new Set([...bi.keys(), ...hi.keys()])) {
      const x = bi.get(k);
      const y = hi.get(k);
      const bv = x?.tokens?.est ?? null;
      const hv = y?.tokens?.est ?? null;
      const d = Math.round((hv ?? 0) - (bv ?? 0));
      if (x && y && d === 0) continue;
      const it = (y ?? x)!;
      changes.push({ key: k, label: it.path ?? it.label ?? it.kind, kind: it.kind, base: x ? bv : null, head: y ? hv : null, delta: d });
    }
    changes.sort((p, q) => Math.abs(q.delta) - Math.abs(p.delta) || p.label.localeCompare(q.label));
    agents.push({
      id,
      name: (h ?? b)!.name,
      base: bt,
      head: ht,
      delta: Math.round(delta),
      deltaPct: bt && bt >= 100 ? Math.round((delta / bt) * 1000) / 10 : null,
      deferredDelta: Math.round(deferredDelta),
      lowerBound: !!(b?.alwaysIsLowerBound || h?.alwaysIsLowerBound),
      changes: changes.slice(0, MAX_ITEMS),
      moreChanges: Math.max(0, changes.length - MAX_ITEMS),
    });
  }
  return { base, head, agents, notes };
}

export function signedTok(n: number): string {
  if (Math.round(n) === 0) return "±0";
  return (n > 0 ? "+" : "−") + fmtTok(Math.abs(n));
}
export function headline(a: AgentDiff): string {
  if (a.base === null) return `${a.name}: new, ~${fmtTok(a.head ?? 0)} tokens before hello`;
  if (a.head === null) return `${a.name}: no longer detected (was ~${fmtTok(a.base)} tokens before hello)`;
  if (a.delta === 0) return `${a.name}: no change, ~${fmtTok(a.head)} tokens before hello`;
  return `${a.name}: ${signedTok(a.delta)} tokens before hello (~${fmtTok(a.base)} → ~${fmtTok(a.head)}${a.deltaPct !== null ? `, ${a.deltaPct > 0 ? "+" : ""}${a.deltaPct}%` : ""})`;
}
const cell = (n: number | null) => (n === null ? "-" : fmtTok(n));
const chg = (c: ItemChange) => (c.base === null ? "added" : c.head === null ? "removed" : "changed");

export function overThreshold(d: DiffResult, max: number): AgentDiff[] {
  return d.agents.filter((a) => a.delta > max);
}

export function renderDiffTerminal(d: DiffResult): string {
  const out = ["prehello diff (estimates; always-on context before your first message)", ""];
  if (!d.agents.length) out.push("No agent context found in either report.");
  for (const a of d.agents) {
    out.push(sanitize(headline(a), 200));
    for (const c of a.changes) out.push(`    ${signedTok(c.delta).padStart(7)}  ${chg(c).padEnd(7)}  ${sanitize(c.label, 80)}`);
    if (a.moreChanges) out.push(`    … ${a.moreChanges} more changed item(s)`);
    if (a.deferredDelta) out.push(`    on demand (skill bodies, deferred tools): ${signedTok(a.deferredDelta)}`);
  }
  for (const n of d.notes) out.push(`note: ${n}`);
  return out.join("\n") + "\n";
}

export function renderDiffMarkdown(d: DiffResult, opts: { threshold?: number } = {}): string {
  const over = opts.threshold !== undefined ? overThreshold(d, opts.threshold) : [];
  const out = [DIFF_MARKER, "### prehello: context before hello", ""];
  const moved = d.agents.filter((a) => a.delta !== 0 || a.base === null || a.head === null);
  if (!d.agents.length) out.push("No agent context (CLAUDE.md, AGENTS.md, rules, skills, MCP) found in this repository.");
  else if (!moved.length) out.push(`No change in always-on context. ${d.agents.map((a) => `${mdCode(a.name)} ~${fmtTok(a.head ?? 0)} tokens`).join(", ")}.`);
  else {
    out.push("| Agent | Base | Head | Change |", "|---|---:|---:|---:|");
    for (const a of d.agents) out.push(`| ${mdCode(a.name, true)} | ${cell(a.base)} | ${cell(a.head)}${a.lowerBound ? " (at least)" : ""} | **${signedTok(a.delta)}**${a.deltaPct !== null && a.delta ? ` (${a.deltaPct > 0 ? "+" : ""}${a.deltaPct}%)` : ""} |`);
    out.push("");
    for (const a of d.agents.filter((x) => x.changes.length)) {
      out.push(`<details><summary>${mdCode(a.name)}: ${a.changes.length + a.moreChanges} changed item(s)</summary>`, "", "| Change | Item | Base | Head |", "|---:|---|---:|---:|");
      for (const c of a.changes) out.push(`| ${signedTok(c.delta)} | ${chg(c)} ${mdCode(c.label, true)} | ${cell(c.base)} | ${cell(c.head)} |`);
      if (a.moreChanges) out.push(`| | … ${a.moreChanges} more | | |`);
      out.push("", "</details>", "");
    }
  }
  if (over.length) out.push("", `**Over the limit:** ${over.map((a) => `${mdCode(a.name)} grew ${signedTok(a.delta)} (limit +${fmtTok(opts.threshold!)})`).join(", ")}.`);
  for (const n of d.notes) out.push("", `_Note: ${sanitize(n, 200).replace(/[_*`<>[\]]/g, " ")}_`);
  out.push("", `<sub>Estimates (o200k-based, per-agent factors), not exact for any model. Only this repository's files are scanned. [prehello](https://${REPO_URL}) ${sanitize(d.head.tool.version, 20)}</sub>`);
  return out.join("\n") + "\n";
}

export function diffJson(d: DiffResult, threshold?: number): object {
  return {
    tool: { name: "prehello", version: d.head.tool.version },
    kind: "diff",
    agents: d.agents,
    notes: d.notes,
    ...(threshold !== undefined ? { threshold, overThreshold: overThreshold(d, threshold).map((a) => a.id) } : {}),
  };
}

/** shields.io endpoint JSON (https://shields.io/badges/endpoint-badge). */
export function badgeJson(name: string, est: number | null, lowerBound: boolean): object {
  const color = est === null ? "lightgrey" : est < 5000 ? "brightgreen" : est < 15000 ? "green" : est < 30000 ? "yellow" : est < 60000 ? "orange" : "red";
  return { schemaVersion: 1, label: "context before hello", message: est === null ? "unmeasured" : `${lowerBound ? "≥" : "~"}${fmtTok(est)} tokens (${name})`, color };
}
