/**
 * Safe output files for --json=<file>, --card=<file>, --markdown=<file> and --sarif=<file>.
 * Rules: never write through a symlink; only replace a regular file that is a previous prehello output
 * (or anything, with --force); never follow a link swapped in between the check and the open (O_NOFOLLOW + fstat identity check).
 * Together with src/cli.ts, this is the only place that writes to disk, and the static test allowlists exactly these two files.
 */
import fs from "node:fs";
import { hasWindowsStream, isWindowsReservedName } from "./platform";

export class SafeWriteError extends Error {}

export type OutputKind = "json" | "svg" | "png" | "md" | "sarif";

/** First line of a markdown report written to a file. An HTML comment: invisible when the file is rendered or pasted into GitHub. */
export const MD_MARKER_PREFIX = "<!-- generated by prehello ";

export interface SafeWriteOpts {
  kind: OutputKind;
  force: boolean;
  /** Platform whose file-name rules apply (default: this host). Tests pass "win32". */
  platform?: NodeJS.Platform;
}

/** True when the first bytes look like something prehello itself wrote. */
export function looksLikePrehelloOutput(headRaw: string, kind: OutputKind): boolean {
  // a Windows editor may have re-saved our file with a UTF-8 BOM (as "\ufeff", or as its three latin1 bytes): still ours
  const head = kind === "png" ? headRaw : headRaw.replace(/^(?:\ufeff|\u00ef\u00bb\u00bf)/, "");
  if (kind === "md") return head.startsWith(MD_MARKER_PREFIX);
  // `head` is decoded as latin1, so a PNG's bytes survive: signature, then the tEXt "Software: prehello" chunk tagPng() adds right after IHDR.
  if (kind === "png") return head.startsWith("\u0089PNG\r\n\u001a\n") && /tEXtSoftware\u0000prehello /.test(head);
  if (kind === "svg") return /^\s*(<\?xml[^>]*>\s*)?<svg[\s>]/.test(head) && /Generated by prehello /.test(head);
  if (kind === "sarif") return /^\s*\{/.test(head) && /"version":\s*"2\.1\.0"/.test(head) && /"driver":\s*\{\s*"name":\s*"prehello"/.test(head);
  return /^\s*\{/.test(head) && /"tool":\s*\{\s*"name":\s*"prehello"/.test(head);
}

/** Friendly text for the errors a Windows (or any) user actually hits when the target is busy, read-only or in a missing folder. */
export function describeWriteError(code: string | undefined): string {
  switch (code) {
    case "ENOENT": return "the folder does not exist (create it first)";
    case "EACCES":
    case "EPERM": return "permission denied (read-only file or folder, or another program such as an editor, sync client or antivirus holds it)";
    case "EBUSY": return "the file is in use by another program; close it and try again";
    case "EISDIR": return "that name is a folder";
    case "ENOSPC": return "the disk is full";
    case "ENAMETOOLONG": return "the path is too long";
    default: return code ?? "error";
  }
}

export function safeWrite(abs: string, content: string | Buffer, opts: SafeWriteOpts): void {
  if ((opts.platform ?? process.platform) === "win32") {
    if (isWindowsReservedName(abs)) throw new SafeWriteError("that is a reserved Windows device name (CON, NUL, COM1, ...); pick another file name");
    if (hasWindowsStream(abs)) throw new SafeWriteError("a ':' in the file name would create a hidden NTFS data stream; pick another file name");
  }
  let st: fs.Stats | null = null;
  let identity: fs.BigIntStats | null = null;
  try {
    st = fs.lstatSync(abs);
    identity = fs.lstatSync(abs, { bigint: true });
  } catch (e) {
    const code = (e as NodeJS.ErrnoException).code;
    if (code !== "ENOENT") throw new SafeWriteError(describeWriteError(code));
  }
  if (st) {
    if (st.isSymbolicLink()) throw new SafeWriteError("it is a symlink; prehello never writes through symlinks (remove the link or pick another name)");
    if (!st.isFile()) throw new SafeWriteError("it exists and is not a regular file");
    if (!opts.force) {
      if (st.nlink > 1) throw new SafeWriteError("it has other hard links; use --force to write anyway");
      let head = "";
      try {
        const fd = fs.openSync(abs, fs.constants.O_RDONLY | (fs.constants.O_NOFOLLOW ?? 0));
        try {
          const buf = Buffer.alloc(4096);
          head = buf.toString("latin1", 0, fs.readSync(fd, buf, 0, buf.length, 0));
        } finally {
          fs.closeSync(fd);
        }
      } catch {
        throw new SafeWriteError("it exists and could not be checked; use --force to replace it");
      }
      if (!looksLikePrehelloOutput(head, opts.kind)) throw new SafeWriteError("it exists and was not written by prehello; use --force to replace it");
    }
  }
  const C = fs.constants;
  const flags = C.O_WRONLY | C.O_CREAT | (C.O_NOFOLLOW ?? 0) | (st ? 0 : C.O_EXCL);
  let fd: number;
  try {
    fd = fs.openSync(abs, flags, 0o644);
  } catch (e) {
    const code = (e as NodeJS.ErrnoException).code;
    if (code === "ELOOP" || code === "EEXIST") throw new SafeWriteError("the path changed while writing (symlink or new file); nothing was written");
    throw new SafeWriteError(describeWriteError(code));
  }
  try {
    // bigint: NTFS file ids do not fit in a double, two different files could otherwise compare equal
    const now = fs.fstatSync(fd, { bigint: true });
    if (!now.isFile() || (st && (now.ino !== (identity?.ino ?? 0n) || now.dev !== (identity?.dev ?? 0n)))) throw new SafeWriteError("the file changed while writing; nothing was written");
    fs.ftruncateSync(fd, 0);
    const buf = typeof content === "string" ? Buffer.from(content, "utf8") : content;
    for (let off = 0; off < buf.length; ) off += fs.writeSync(fd, buf, off, buf.length - off);
  } finally {
    fs.closeSync(fd);
  }
}
