// Writes src/version.ts from package.json so the CLI version has one source of truth.
import { readFileSync, writeFileSync } from "node:fs";
const v = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8")).version;
const out = `// Generated by scripts/gen-version.mjs from package.json. Do not edit.\nexport const VERSION = ${JSON.stringify(v)};\n`;
const f = new URL("../src/version.ts", import.meta.url);
let cur = "";
try { cur = readFileSync(f, "utf8"); } catch {}
if (cur !== out) writeFileSync(f, out);
