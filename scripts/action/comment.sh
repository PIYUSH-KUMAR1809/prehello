#!/usr/bin/env bash
# Create or update ONE comment on the PR, found by the marker on its first line. On a fork PR (read-only token) this
# warns and succeeds: the job summary already has the same text.
set -euo pipefail
out="${RUNNER_TEMP:?}/prehello"
marker='<!-- generated by prehello diff -->'
body="$out/comment.md"
api() { gh api -H "Accept: application/vnd.github+json" "$@"; }
id=$(api "repos/${REPO:?}/issues/${PR_NUMBER:?}/comments" --paginate --jq ".[] | select(.body | startswith(\"$marker\")) | .id" 2>/dev/null | head -n1 || true)
payload="$out/payload.json"
node -e 'process.stdout.write(JSON.stringify({body:require("fs").readFileSync(process.argv[1],"utf8")}))' "$body" > "$payload"
# update ours; if that fails (someone else's comment carries the marker), post a new one
if [ -n "$id" ] && api -X PATCH "repos/$REPO/issues/comments/$id" --input "$payload" >/dev/null 2>&1; then exit 0; fi
if api -X POST "repos/$REPO/issues/$PR_NUMBER/comments" --input "$payload" >/dev/null 2>&1; then exit 0; fi
echo "::warning::prehello could not comment on the PR (a fork PR gets a read-only token). The result is in the job summary."
